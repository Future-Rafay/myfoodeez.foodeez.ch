CREATE TABLE IF NOT EXISTS business_discount (
  DISCOUNT_ID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  BUSINESS_ID INT NOT NULL,
  NAME VARCHAR(100) NOT NULL,
  TYPE VARCHAR(20) NOT NULL,
  VALUE DECIMAL(8,2) NOT NULL,
  MINIMUM_ORDER DECIMAL(8,2) NULL,
  ACTIVE TINYINT NOT NULL DEFAULT 0,
  POS_ENABLED TINYINT NOT NULL DEFAULT 0,
  ONLINE_ENABLED TINYINT NOT NULL DEFAULT 0,
  ONLINE_AUTOMATIC TINYINT NOT NULL DEFAULT 0,
  VALID_FROM DATE NULL,
  VALID_UNTIL DATE NULL,
  CREATION_DATETIME DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY business_discount_business_name_unique (BUSINESS_ID, NAME),
  KEY idx_business_discount_business_active (BUSINESS_ID, ACTIVE)
);

CREATE TABLE IF NOT EXISTS business_discount_code (
  CODE_ID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  BUSINESS_ID INT NOT NULL,
  DISCOUNT_ID INT NOT NULL,
  CODE VARCHAR(64) NOT NULL,
  ACTIVE TINYINT NOT NULL DEFAULT 1,
  UNIQUE KEY business_discount_code_business_code_unique (BUSINESS_ID, CODE),
  KEY idx_business_discount_code_discount (DISCOUNT_ID)
);

